# Where things live
# =============================================================================

def install_mode(app_dir: Path) -> str:
    return "git" if (Path(app_dir) / ".git").exists() else "zip"


def staged_root(app_dir: Path) -> Path:
    return ua.updates_dir(app_dir) / "staged"


def find_staged(app_dir: Path, current_version: str) -> Optional[Path]:
    """The newest staged update still worth installing, or None."""
    root = staged_root(app_dir)
    if not root.is_dir():
        return None
    best, best_v = None, current_version
    for d in root.iterdir():
        payload = ua.read_json(d / "payload.json")
        if not isinstance(payload, dict):
            continue
        v = str(payload.get("version") or "")
        if not ua.is_newer(v, best_v) or ua.is_bad(app_dir, v):
            continue
        if payload.get("mode") != install_mode(app_dir):
            continue
        if payload.get("mode") == "zip" and not (d / "files").is_dir():
            continue
        best, best_v = d, v
    return best


def needs_pip(app_dir: Path, staged: Path) -> bool:
    payload = ua.read_json(staged / "payload.json", {}) or {}
    want = payload.get("requirements_sha256")
    return bool(want) and want != ua.requirements_sha(app_dir)


def prune_staged(app_dir: Path, keep: Optional[Path]) -> None:
    root = staged_root(app_dir)
    if not root.is_dir():
        return
    for d in root.iterdir():
        if keep is None or d.resolve() != keep.resolve():
            shutil.rmtree(d, ignore_errors=True)


# =============================================================================
# Checking GitHub
# =============================================================================

def _http_get(url: str, *, accept: str, max_bytes: int) -> bytes:
    import requests
    headers = {"Accept": accept, "User-Agent": f"{APP_ID}-updater"}
    with requests.get(url, headers=headers, timeout=HTTP_TIMEOUT, stream=True) as r:
        r.raise_for_status()
        buf = bytearray()
        for chunk in r.iter_content(1 << 16):
            buf += chunk
            if len(buf) > max_bytes:
                raise UpdateError(f"download larger than {max_bytes} bytes: {url}")
        return bytes(buf)


def check_and_stage(app_dir: Path, current_version: str,
                    log: Callable[[str], None] = lambda m: None,
                    *, http_get: Callable[..., bytes] = _http_get,
                    public_key_b64: Optional[str] = None) -> Optional[Path]:
    """Download and stage the latest release if it is newer. Returns the
    staged folder, or None when there is nothing to install. Never raises."""
    app_dir = Path(app_dir)
    try:
        return _check_and_stage(app_dir, current_version, log, http_get, public_key_b64)
    except UpdateError as exc:
        log(f"Update: skipped — {exc}")
    except Exception as exc:                    # noqa: BLE001 — offline, GitHub down
        log(f"Update: could not check for a new version ({type(exc).__name__}: {exc})")
    return None


def _check_and_stage(app_dir: Path, current_version: str, log, http_get,
                     public_key_b64) -> Optional[Path]:
    mode = install_mode(app_dir)
    if mode == "git":
        reason = ua.git_unfit_reason(app_dir)
        if reason:
            log(f"Update: not automatic here — this folder is a git checkout that {reason}")
            return None

    release = json.loads(http_get(LATEST_URL, accept="application/vnd.github+json",
                                  max_bytes=MAX_PAYLOAD_BYTES))
    tag = str(release.get("tag_name") or "")
    version = tag.lstrip("vV")
    if not ua.is_newer(version, current_version):
        return None
    if ua.is_bad(app_dir, version):
        return None
    existing = find_staged(app_dir, current_version)
    if existing is not None and existing.name == version:
        return existing

    assets = {a.get("name"): a.get("browser_download_url")
              for a in release.get("assets") or [] if isinstance(a, dict)}
    sig_name = f"{APP_ID}-{tag}.update.json"
    if not assets.get(sig_name):
        raise UpdateError(f"{tag} has no signed {sig_name}")
    doc = json.loads(http_get(assets[sig_name], accept="application/octet-stream",
                              max_bytes=MAX_PAYLOAD_BYTES))
    payload = verify_payload(doc, public_key_b64)
    if payload["tag"] != tag:
        raise UpdateError(f"signed payload is for {payload['tag']}, release is {tag}")

    staging = staged_root(app_dir) / (version + ".partial")
    final = staged_root(app_dir) / version
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    if mode == "zip":
        if not assets.get(payload["zip_name"]):
            raise UpdateError(f"{tag} has no {payload['zip_name']}")
        log(f"Update: downloading {tag}")
        zip_bytes = http_get(assets[payload["zip_name"]],
                             accept="application/octet-stream", max_bytes=MAX_ZIP_BYTES)
        extract_verified(zip_bytes, payload, staging / "files")
    else:
        # Fetch the tag now, while the app is up and online, so the install
        # at the next start needs no network at all.
        try:
            ua.git_prepare(app_dir, payload)
        except RuntimeError as exc:
            raise UpdateError(str(exc)) from None
    payload = dict(payload, mode=mode, from_version=current_version)
    ua.write_json(staging / "payload.json", payload)
    shutil.rmtree(final, ignore_errors=True)
    os.replace(staging, final)
    prune_staged(app_dir, keep=final)
    log(f"Update: {tag} is ready and installs at the next quiet moment")
    return final


# =============================================================================
# Handing over to update_apply
# =============================================================================

def launch_installer(app_dir: Path, staged: Path, pythonw: Optional[str] = None,
                     *, popen: Optional[Callable[..., Any]] = None) -> None:
    """Start update_apply from a COPY outside the install folder; it waits for
    this process to exit before it touches anything.

    The staged folder is moved out of updates/staged/ first, so a check that
    stages a newer release in the meantime cannot prune it from under the
    installer. The journal is written here, before this process exits, so a
    copy started by hand in the moment before the installer writes its own
    already sees an install under way.
    """
    app_dir = Path(app_dir)
    run_dir = ua.updates_dir(app_dir) / "run"
    run_dir.mkdir(parents=True, exist_ok=True)
    helper = run_dir / "update_apply.py"
    shutil.copy2(Path(ua.__file__), helper)
    installing = run_dir / f"install-{Path(staged).name}"
    shutil.rmtree(installing, ignore_errors=True)
    os.replace(staged, installing)
    pyw = pythonw or sys.executable
    cmd = [pyw, str(helper), "--app-dir", str(app_dir), "--staged", str(installing),
           "--pid", str(os.getpid()), "--pythonw", pyw]
    proc = (popen or ua.popen_detached)(cmd, cwd=str(run_dir), close_fds=True)
    pid = getattr(proc, "pid", 0) or 0
    payload = ua.read_json(installing / "payload.json", {}) or {}
    ua.write_json(ua.journal_path(app_dir), ua.new_journal(
        app_dir, installing, payload, pid, ua.process_created(pid) if pid else None))


def startup_recover(app_dir: Path) -> str:
    """Run in __main__ BEFORE the single-instance lock.

    'busy'    an install is under way: do not start (and do not take the
              lock, or the copy the installer launches would lose it).
    'restart' an interrupted install was just undone; this process may hold
              half-new code, so start a clean one.
    'run'     carry on.
    """
    try:
        rec = ua.recover(Path(app_dir), ua.Log(Path(app_dir)))
    except Exception:                           # noqa: BLE001 — never block a start
        return "run"
    return {"busy": "busy", "rolled-back": "restart"}.get(rec or "", "run")


def startup_install(app_dir: Path, current_version: str,
                    log: Callable[[str], None] = lambda m: None) -> bool:
    """Run in __main__ after the single-instance lock, before any window.
    True when the installer was launched and this process must exit now."""
    app_dir = Path(app_dir)
    try:
        if not enabled():
            return False
        staged = find_staged(app_dir, current_version)
        if staged is None or needs_pip(app_dir, staged):
            return False
        if install_mode(app_dir) == "git":
            if ua.git_unfit_reason(app_dir):
                return False
            payload = ua.read_json(staged / "payload.json", {}) or {}
            ua.git_prepare(app_dir, payload, fetch=False)   # no network at start
        log(f"Update: installing {staged.name} before start")
        launch_installer(app_dir, staged)
        return True
    except Exception as exc:                    # noqa: BLE001 — never block a start
        log(f"Update: not installing at start ({exc})")
        return False


def write_healthy(app_dir: Path, current_version: str) -> None:
    """Called by the App once its window has been up for a while. The
    installer is watching for this file to decide whether to roll back."""
    if os.environ.get("RSA_UPDATE_EXPECT") != current_version:
        return
    ua.write_json(ua.updates_dir(app_dir) / ua.HEALTHY_NAME,
                  {"version": current_version, "pid": os.getpid(),
                   "at": datetime.now().isoformat(timespec="seconds")})


