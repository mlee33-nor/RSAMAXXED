def quiet_hours(now_et: Optional[datetime]) -> bool:
    """True when nobody is trading: a weekend or market holiday, or between
    20:00 and 04:00 Eastern on a trading day. Unknown time -> False."""
    if now_et is None:
        return False
    try:
        from modules import market_calendar as mc
        if mc.covered(now_et.date()) and not mc.is_trading_day(now_et.date()):
            return True
    except Exception:                           # noqa: BLE001
        pass
    if now_et.weekday() >= 5:
        return True
    t = now_et.time()
    return t >= QUIET_FROM or t < QUIET_UNTIL


class IdleClock:
    """How long the app has been continuously idle. `busy` is sampled by the
    caller; any busy sample restarts the clock."""

    def __init__(self, now: Callable[[], float]):
        self._now = now
        self._since: Optional[float] = None

    def sample(self, busy: bool) -> float:
        t = self._now()
        if busy:
            self._since = None
            return 0.0
        if self._since is None:
            self._since = t
        return t - self._since


class Checker:
    """Background check-and-stage on a worker thread, one at a time."""

    def __init__(self, app_dir: Path, current_version: str,
                 log: Callable[[str], None]):
        self.app_dir = Path(app_dir)
        self.version = current_version
        self.log = log
        self._lock = threading.Lock()

    def start(self) -> bool:
        if not enabled() or not self._lock.acquire(blocking=False):
            return False

        def _run() -> None:
            try:
                check_and_stage(self.app_dir, self.version, self.log)
            finally:
                self._lock.release()

        threading.Thread(target=_run, name="update-check", daemon=True).start()
        return True
