"""Silent updates: find a new release, prove it is ours, install it quietly.

HOW IT FLOWS
------------
1. A few minutes after start, then every few hours, `check_and_stage()` (on a
   worker thread) asks GitHub for the latest release of the public repo. When
   it is newer than APP_VERSION it downloads the release's signed
   `RSAMAXXED-vX.Y.Z.update.json`, checks the Ed25519 signature against the
   public key below, and stages the update under updates/staged/<version>/:
   the zip unpacked and every file checked against its signed hash (ZIP
   installs), or just the verified payload (git checkouts, which install with
   a fast-forward to the signed tag instead).
2. The install itself happens with the app closed (modules/update_apply.py):
   * at the next launch, before any window, when the update needs no pip
     install (a few seconds; nothing trading yet), or
   * overnight / on a market holiday or weekend, once the app has been idle
     -- no order out, no mirror run, no sell queue, no broker sign-in -- for
     IDLE_BEFORE_INSTALL_S.
   Restarting is not free: Robinhood or Wells Fargo may want a phone approval
   again, and a restart mid-trade lost legs on 2026-09-29. So a running app is
   only ever restarted at a quiet hour, never during a trading session.

WHY A SIGNATURE, NOT JUST HTTPS
-------------------------------
This pushes code onto every customer's PC, next to their broker logins. HTTPS
only proves the download came from GitHub; anyone who gets into the GitHub
account could publish a release. The private key that signs releases never
leaves the operator's PC (release.py), so a release it did not sign is
refused no matter where it came from.

OPTING OUT
----------
RSA_AUTO_UPDATE=false in .env turns all of this off. A git checkout with local
changes, or on a branch other than main, is never touched (that is someone
working in the folder -- the operator's own repo is one).
"""
from __future__ import annotations

import base64
import io
import json
import os
import shutil
import sys
import threading
import zipfile
from datetime import datetime, time as dtime
from pathlib import Path
from typing import Any, Callable, Dict, Optional

from modules import update_apply as ua

#: The repo releases are published to.
REPO = "mlee33-nor/RSAMAXXED"
LATEST_URL = f"https://api.github.com/repos/{REPO}/releases/latest"

#: Raw Ed25519 public key (base64) matching the operator's release signing key.
#: Generated by `py -3.13 release.py --init-key`; never the private half.
PUBLIC_KEY_B64 = "ogp/9MjJ2jToKJict+N2nqhb7wa2W38N9tHTbkuIF20="

#: What a signed payload must say it is.
APP_ID = "RSAMAXXED"

FIRST_CHECK_DELAY_S = 3 * 60
CHECK_EVERY_S = 6 * 60 * 60
#: How long the app must have been idle before a quiet-hours restart.
IDLE_BEFORE_INSTALL_S = 10 * 60
#: Size caps: the payload is a few KB, the zip a few MB.
MAX_PAYLOAD_BYTES = 4 * 1024 * 1024
MAX_ZIP_BYTES = 200 * 1024 * 1024
HTTP_TIMEOUT = (10, 60)

#: Quiet hours (US/Eastern) on a trading day: after the after-hours session
#: ends and before the pre-market one starts.
QUIET_FROM = dtime(20, 0)
QUIET_UNTIL = dtime(4, 0)


class UpdateError(Exception):
    """A release that must not be installed. The message says why."""


def enabled() -> bool:
    raw = (os.environ.get("RSA_AUTO_UPDATE") or "").strip().lower()
    return raw not in ("0", "false", "no", "off")


# =============================================================================
# Verifying a release
# =============================================================================

def verify_payload(doc: Dict[str, Any], public_key_b64: Optional[str] = None
                   ) -> Dict[str, Any]:
    """The signed payload inside an .update.json, or UpdateError.

    The signature covers the exact payload bytes; nothing outside them is
    trusted.
    """
    key_b64 = public_key_b64 or PUBLIC_KEY_B64
    try:
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    except ImportError as exc:                  # pragma: no cover — a dep of robin-stocks
        raise UpdateError(f"cannot check signatures: {exc}") from exc
    try:
        key = Ed25519PublicKey.from_public_bytes(base64.b64decode(key_b64, validate=True))
        raw = base64.b64decode(doc["payload"], validate=True)
        sig = base64.b64decode(doc["signature"], validate=True)
    except Exception as exc:                    # noqa: BLE001
        raise UpdateError(f"malformed update file: {exc}") from exc
    try:
        key.verify(sig, raw)
    except InvalidSignature:
        raise UpdateError("signature does not match: not a release we signed") from None
    try:
        payload = json.loads(raw.decode("utf-8"))
    except ValueError as exc:
        raise UpdateError(f"payload is not JSON: {exc}") from exc
    if not isinstance(payload, dict) or payload.get("app") != APP_ID:
        raise UpdateError("payload is not an RSAMAXXED release")
    version = str(payload.get("version") or "")
    if not ua.parse_version(version) or payload.get("tag") != f"v{version}":
        raise UpdateError(f"payload names no usable version: {version!r}")
    files = payload.get("files")
    if not isinstance(files, dict) or not files:
        raise UpdateError("payload lists no files")
    for rel in files:
        try:
            ua.check_rel_path(rel)
        except ValueError as exc:
            raise UpdateError(str(exc)) from None
    for key_name in ("zip_name", "zip_sha256", "git_tree"):
        if not isinstance(payload.get(key_name), str) or not payload[key_name]:
            raise UpdateError(f"payload has no {key_name}")
    return payload


def extract_verified(zip_bytes: bytes, payload: Dict[str, Any], dest: Path) -> None:
    """Unpack the release zip into `dest`, refusing anything that is not
    exactly the signed file list with the signed hashes."""
    if ua.sha256_bytes(zip_bytes) != payload["zip_sha256"]:
        raise UpdateError("downloaded zip does not match the signed hash")
    files: Dict[str, str] = payload["files"]
    with zipfile.ZipFile(io.BytesIO(zip_bytes)) as zf:
        members = [i for i in zf.infolist() if not i.is_dir()]
        names = {i.filename for i in members}
        if names != set(files):
            raise UpdateError("zip contents differ from the signed file list")
        if dest.exists():
            shutil.rmtree(dest)
        for info in members:
            rel = ua.check_rel_path(info.filename)
            data = zf.read(info)
            if ua.sha256_bytes(data) != files[rel]:
                raise UpdateError(f"{rel} does not match its signed hash")
            out = dest / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(data)


